export function localizeText(text: string, language: Language): string {
  return language === 'am' ? (textMap[text] ?? text) : text
}

interface LanguageContextValue {
  language: Language
  setLanguage: (language: Language) => void
  toggleLanguage: () => void
  t: (key: TranslationKey, values?: TranslateValues) => string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

function subscribeLanguage(onChange: () => void) {
  window.addEventListener('storage', onChange)
  return () => window.removeEventListener('storage', onChange)
}

function getLanguageSnapshot(): Language {
  const saved = window.localStorage.getItem(STORAGE_KEY)
  return saved === 'am' || saved === 'en' ? saved : 'en'
}

function getServerLanguageSnapshot(): Language {
  return 'en'
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const storedLanguage = useSyncExternalStore(
    subscribeLanguage,
    getLanguageSnapshot,
    getServerLanguageSnapshot,
  )
  const [override, setOverride] = useState<Language | null>(null)
  const language = override ?? storedLanguage

  const setLanguage = useCallback((next: Language) => {
    window.localStorage.setItem(STORAGE_KEY, next)
    setOverride(next)
  }, [])

  const toggleLanguage = useCallback(
    () => setLanguage(language === 'en' ? 'am' : 'en'),
    [language, setLanguage],
  )

  useEffect(() => {
    document.documentElement.lang = language
  }, [language])

  const value = useMemo<LanguageContextValue>(
    () => ({
      language,
      setLanguage,
      toggleLanguage,
      t: (key, values) => translate(key, language, values),
    }),
    [language, setLanguage, toggleLanguage],
  )

  return (
    <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
  )
}

export function useLanguage(): LanguageContextValue {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider')
  return context
}

export function T({ k, values }: { k: TranslationKey; values?: TranslateValues }) {
  const { t } = useLanguage()
  return <>{t(k, values)}</>
}

export function Localized({ text }: { text: string }) {
  const { language } = useLanguage()
  return <>{localizeText(text, language)}</>
}

export function CategoryDescription({ category }: { category: string }) {
  const { language, t } = useLanguage()
  return (
    <>
      {t('category.description', {
        category: localizeText(category.toLowerCase(), language),
      })}
    </>
  )
}
